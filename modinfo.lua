description = [[强化手柄功能 - 自定义组合键、视角控制和智能寻路

核心功能：
• 游戏内配置界面 (键盘: Ctrl+K, 手柄: LB+RB+Y 同时按)
• 可自定义 12 种按钮组合的行为 (LB/RB + A/B/X/Y/LT/RT)
• 支持多动作序列和参数化动作
• 动作间自动延迟 (0.3秒)，支持联机同步
• 配置自动保存并在重启后加载
• 完整的手柄操作支持

地图寻路功能：
• 打开地图后启用虚拟光标 (LB+RB+RT)
• 点击地图任意位置自动寻路
• 智能规避海洋和障碍物
• 沿海岸线自动寻找绕路
• 单机和联机模式均可用
• 实时路径可视化

虫洞追踪功能 (NEW!)：
• 自动记录虫洞配对关系
• 地图上显示配对编号 (相同数字 = 一对)
• 数据持久化保存 (每个世界独立)
• 无需手动标记

自动建造功能：
• 搜索附近地面物品和可打开储物容器
• 制作动作可按中文名、英文名或内部名搜索全部有效配方
• 自动收录当前游戏和其他 Mod 添加的配方
• 装备及物品使用动作同样支持中英文物品搜索
• 按世界与洞穴分片缓存上次查看的容器内容
• 自动制作次级材料，并优先降低背包峰值占用
• 可用科技会通过原生原型制作自动解锁
• 缓存不符或任务被打断时立即停止，不自动回滚

搜索烹饪功能：
• 原菜谱书入口替换为不暂停移动的半屏烹饪列表
• 不依赖菜谱解锁记录，按当前实际材料动态规划四格组合
• 可将“打开烹饪列表”配置到任意模组组合键
• 自动查找附近食材、储物容器与兼容空锅
• 逐格验证食材后调用原生烹饪按钮

视角控制：
• LB + 右摇杆左右: 旋转视角
• LB + 右摇杆上下: 缩放视角
• 地图模式支持缩放和旋转

可用动作包括：
• 装备切换、物品使用
• 检查、制作
• 自定义参数动作

使用说明：
1. 打开配置界面 (键盘: Ctrl+K, 手柄: LB+RB+Y)
2. 选择要配置的按钮组合
3. 添加按下/松开时的动作序列
4. 点击应用保存配置

配置文件位置：
client_save/enhanced_controller_config.json
